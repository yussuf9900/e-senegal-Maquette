async (page) => {
  const errors = [];
  const checks = [];
  page.on('pageerror', error => errors.push(error.message));
  const check = (name, pass, detail = '') => {
    checks.push({name, pass: Boolean(pass), detail});
    if (!pass) throw new Error(name + ': ' + detail);
  };
  const route = async path => {
    await page.evaluate(path => { location.hash = path; }, path);
    await page.waitForTimeout(300);
  };
  await page.goto('http://127.0.0.1:4187');
  await page.evaluate(() => { localStorage.clear(); });
  await page.reload();
  await page.setViewportSize({width:1440,height:1000});
  await page.waitForTimeout(1500);
  check('Splash retiré', await page.locator('.intro').count() === 0);
  await page.locator('#hero-search input').fill('extrait de naissance');
  await page.locator('#hero-search button').click();
  await page.locator('#results .procedure-card').waitFor();
  check('Recherche principale', await page.locator('#results .procedure-card').count() === 1);
  await page.locator('#results .procedure-card').click();
  await page.getByRole('link', {name:'Commencer la démarche',exact:true}).click();
  await page.locator('#login-form').waitFor();
  await page.locator('#login-form button').click();
  check('Connexion invalide', (await page.locator('#login-error').textContent()).length > 0);
  await page.locator('#autofill').click();
  await page.locator('#login-form button').click();
  await page.locator('#information-form').waitFor();
  await page.locator('#information-form button').click();
  check('Validation et focus', await page.locator('[aria-invalid=true]').count() === 4 && await page.locator('#firstName').evaluate(el => el === document.activeElement));
  await page.locator('#firstName').fill('Youssou');
  await page.locator('#lastName').fill('Diop');
  await page.locator('#birthDate').fill('1998-06-15');
  await page.locator('#reference').fill('DEMO-2026-042');
  await page.locator('#information-form button').click();
  await page.locator('#documents-next').click();
  check('Document obligatoire', (await page.locator('#upload-error').textContent()).includes('Ajoutez'));
  await page.locator('#file-input').setInputFiles({name:'invalide.txt',mimeType:'text/plain',buffer:Buffer.from('demo')});
  check('Type de fichier refusé', (await page.locator('#upload-error').textContent()).includes('PDF'));
  await page.locator('#file-input').setInputFiles({name:'trop-grand.pdf',mimeType:'application/pdf',buffer:Buffer.alloc(6*1024*1024)});
  check('Fichier > 5 Mo refusé', (await page.locator('#upload-error').textContent()).includes('5 Mo'));
  await page.locator('#file-input').setInputFiles({name:'piece-fictive.pdf',mimeType:'application/pdf',buffer:Buffer.from('%PDF-1.4 demo fictive')});
  await page.waitForTimeout(650);
  check('Fichier local accepté', await page.locator('.file-row').count() === 1);
  await page.locator('[data-remove-file]').click();
  check('Suppression fichier', await page.locator('.file-row').count() === 0);
  await page.locator('#demo-file').click();
  await page.waitForTimeout(650);
  await page.locator('#documents-next').click();
  await page.locator('[data-step="0"]').click();
  check('Retour récapitulatif sans perte', await page.locator('#firstName').inputValue() === 'Youssou');
  await page.locator('#information-form button').click();
  await page.locator('#documents-next').click();
  await page.locator('#submit-application').click();
  check('Déclaration obligatoire', (await page.locator('#declaration-error').textContent()).length > 0);
  await page.locator('#declaration').check();
  await page.locator('#submit-application').click();
  await page.locator('.reference-number').waitFor();
  check('Référence de démonstration', await page.locator('.reference-number').textContent() === 'ES-2026-001247');
  await page.getByRole('link',{name:'Suivre mon dossier',exact:true}).click();
  await page.locator('#simulate-complement').click();
  check('Complément requis', (await page.locator('.page-heading .badge').textContent()).includes('Complément requis'));
  await page.locator('#demo-file').click();
  await page.waitForTimeout(650);
  await page.locator('#send-complement').click();
  check('Retour en étude', (await page.locator('.page-heading .badge').textContent()).includes('En étude'));
  check('Timeline mise à jour', (await page.locator('.timeline').textContent()).includes('Complément reçu'));
  await route('/procedures');
  await page.locator('[name=cost]').selectOption('free');
  check('Filtre gratuit', await page.locator('#results .procedure-card').count() === 3);
  await page.locator('[name=online]').selectOption('1');
  check('Filtres combinés', await page.locator('#results .procedure-card').count() === 2);
  await page.locator('[name=q]').fill('aucune correspondance xyz');
  check('Aucun résultat', await page.locator('#results .empty').count() === 1);
  await page.locator('#reset').click();
  check('Réinitialisation', await page.locator('#results .procedure-card').count() === 9);
  await page.locator('[name=sort]').selectOption('days');
  check('Tri délai', await page.locator('#results .procedure-card').first().getAttribute('href') === '#/procedures/residence');
  await route('/applications');
  await page.locator('[name=status]').selectOption('BROUILLON');
  check('Dossiers vides', await page.locator('#application-results .empty').count() === 1);
  await route('/help');
  await page.locator('#help-search').fill('documents');
  check('Recherche FAQ', await page.locator('#faq-list details').count() === 1);
  await page.locator('#assistance').click();
  check('Dialogue ouvert', await page.locator('dialog').isVisible());
  await page.keyboard.press('Escape');
  await page.locator('dialog').waitFor({state:'detached'});
  check('Dialogue fermé et focus restauré', await page.locator('dialog').count() === 0 && await page.locator('#assistance').evaluate(el => el === document.activeElement));
  await route('/profile');
  await page.locator('#firstName').fill('Test');
  await page.locator('#profile-form button').click();
  await route('/dashboard');
  check('Profil actualisé', (await page.locator('h1').textContent()).includes('Test'));
  await page.locator('#language').selectOption('wo');
  check('Wolof actif', await page.locator('html').getAttribute('lang') === 'wo' && (await page.locator('h1').textContent()).includes('Nanga def'));
  await route('/applications/new?procedure=naissance');
  check('Parcours Wolof', (await page.locator('.stepper').textContent()).includes('Xibaar yi'));
  await page.locator('#language').selectOption('fr');
  await page.locator('.theme-toggle').click();
  await page.waitForTimeout(300);
  check('Thème sombre', await page.locator('html').getAttribute('data-theme') === 'dark');
  const routes=['/','/procedures','/procedures/naissance','/dashboard','/applications','/applications/ES-2026-001247','/profile','/help','/inconnue'];
  for(const width of [360,390,768,1024,1280,1440,1920]){
    await page.setViewportSize({width,height:900});
    for(const path of routes){
      await route(path);
      const sizes=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth}));
      check(`Responsive ${width} ${path}`,sizes.scroll<=sizes.width,JSON.stringify(sizes));
    }
  }
  await page.emulateMedia({reducedMotion:'reduce'});
  await route('/');
  check('Réduction des animations', await page.locator('.motion-ready:not(.visible)').count()===0);
  await page.setViewportSize({width:1440,height:1000});
  await page.keyboard.press('Tab');
  check('Focus clavier visible', await page.evaluate(()=>document.activeElement !== document.body));
  check('Stockage limité aux préférences', await page.evaluate(()=>Object.keys(localStorage).every(key=>['es-theme','es-language','es-intro'].includes(key))));
  await page.reload();
  check('Préférences persistantes', await page.locator('html').getAttribute('data-theme')==='dark');
  await route('/dashboard');
  check('Session non persistante', page.url().endsWith('#/login'));
  check('Aucune erreur JavaScript', errors.length===0,errors.join('; '));
  return {passed:checks.length,checks,errors};
}
